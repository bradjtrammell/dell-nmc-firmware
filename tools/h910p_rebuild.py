#!/usr/bin/env python3
"""Offline-only Dell H910P NET+OS/LZSS2 firmware rebuild laboratory.

Never uploads firmware. Generated bytes have .offline-test-image extension,
not a vendor-installable .bin, and are NOT approved for device flashing.
"""
from __future__ import annotations

import argparse
from collections import deque
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import struct
import sys
import zipfile

HEADER_STRUCT = struct.Struct('>II8sIIIII')
HEADER_LEN = HEADER_STRUCT.size
POLY = 0x04C11DB7
MAX_APP_BYTES = 32 * 1024 * 1024
MAX_INPUT_BYTES = 16 * 1024 * 1024


def _crc_table() -> tuple[int, ...]:
    table = []
    for value in range(256):
        crc = value << 24
        for _ in range(8):
            crc = ((crc << 1) ^ (POLY if crc & 0x80000000 else 0)) & 0xFFFFFFFF
        table.append(crc)
    return tuple(table)


CRC_TABLE = _crc_table()


def crc32_netos(data: bytes) -> int:
    crc = 0
    for byte in data:
        crc = ((crc << 8) ^ CRC_TABLE[((crc >> 24) ^ byte) & 0xFF]) & 0xFFFFFFFF
    return crc


class ValidationError(ValueError):
    pass


@dataclass(frozen=True)
class Image:
    original: bytes
    header: bytes
    compressed: bytes
    unpacked: bytes
    flash_offset: int
    ram_address: int


def unpack_lzss2(compressed: bytes) -> bytes:
    ring = bytearray(b' ' * 4096)
    write = 0xFEE
    out = bytearray()
    offset = 0
    while offset < len(compressed):
        flags = compressed[offset]
        offset += 1
        for bit in range(8):
            if offset == len(compressed):
                return bytes(out)
            if flags & (1 << bit):
                c = compressed[offset]
                offset += 1
                out.append(c)
                ring[write] = c
                write = (write + 1) & 4095
            else:
                if offset + 2 > len(compressed):
                    raise ValidationError('Truncated back-reference')
                lo, hi = compressed[offset], compressed[offset + 1]
                offset += 2
                pointer = lo | ((hi & 0xF0) << 4)
                length = (hi & 0xF) + 3
                for j in range(length):
                    c = ring[(pointer + j) & 4095]
                    out.append(c)
                    ring[write] = c
                    write = (write + 1) & 4095
            if len(out) > MAX_APP_BYTES:
                raise ValidationError('Decompressed application exceeds maximum size')
    return bytes(out)


def pack_lzss2(unpacked: bytes, max_candidates: int = 1024) -> bytes:
    """Generate compatible LZSS2 stream from a 4 KiB sliding dictionary.

    This is a canonical *alternative* encoder, not a byte-identical
    recreation of Dell's historical compressor. It supports overlapping
    backreferences. It intentionally does not use the prefilled-space
    dictionary optimization (initial bytes are emitted as literals).
    """
    if len(unpacked) > MAX_APP_BYTES:
        raise ValidationError('Application exceeds maximum size')
    if max_candidates < 1:
        raise ValidationError('max_candidates must be positive')
    history: dict[int, deque[int]] = {}
    size = len(unpacked)
    cursor = 0
    indexed_upto = 0
    output = bytearray()

    def keyat(i: int) -> int:
        return (unpacked[i] << 16) | (unpacked[i+1] << 8) | unpacked[i+2]

    def index_through(bound: int) -> None:
        nonlocal indexed_upto
        while indexed_upto < bound:
            ix = indexed_upto
            if ix >= 4096 and ix - 4096 + 2 < size:
                oldkey = keyat(ix - 4096)
                q = history.get(oldkey)
                if q is not None:
                    if q and q[0] == ix - 4096:
                        q.popleft()
                    if not q:
                        del history[oldkey]
            if ix + 2 < size:
                k = keyat(ix)
                history.setdefault(k, deque()).append(ix)
            indexed_upto += 1

    while cursor < size:
        flags = 0
        tokens = bytearray()
        for bit in range(8):
            if cursor >= size:
                break
            best_len = 0
            best_ptr = 0
            if cursor + 2 < size:
                bucket = history.get(keyat(cursor))
                if bucket:
                    scanned = 0
                    for old in reversed(bucket):
                        distance = cursor - old
                        if distance > 4096:
                            break
                        scanned += 1
                        if scanned > max_candidates:
                            break
                        limit = min(18, size-cursor)
                        n = 3
                        # The source is cyclic for overlapping dictionary copies.
                        while n < limit and unpacked[old + n] == unpacked[cursor + n]:
                            n += 1
                        if n > best_len:
                            best_len = n
                            best_ptr = (0xFEE + old) & 0xFFF
                            if n == 18:
                                break
            if best_len >= 3:
                tokens.append(best_ptr & 0xFF)
                tokens.append(((best_ptr >> 4) & 0xF0) | (best_len - 3))
                step = best_len
            else:
                flags |= 1 << bit
                tokens.append(unpacked[cursor])
                step = 1
            cursor += step
            index_through(cursor)
        output.append(flags)
        output.extend(tokens)
    return bytes(output)


def read_image(original: bytes) -> Image:
    if len(original) > MAX_INPUT_BYTES:
        raise ValidationError('Image exceeds limit')
    if len(original) < HEADER_LEN+4:
        raise ValidationError('Too short')
    a, b, magic, ver, flags, flash, ram, payload_size = HEADER_STRUCT.unpack_from(original)
    if a != HEADER_LEN or b != HEADER_LEN or magic != b'bootHdr\0':
        raise ValidationError('Unknown boot image header')
    if ver != 2 or flags != 9 or payload_size != len(original)-HEADER_LEN-4:
        raise ValidationError('Unsupported version, flags, or payload length')
    if crc32_netos(original) != 0:
        raise ValidationError('Invalid firmware CRC')
    compressed = original[HEADER_LEN:-4]
    unpacked = unpack_lzss2(compressed)
    if not unpacked.startswith(bytes.fromhex('e59ff038e1a00000')):
        raise ValidationError('Unsupported application startup')
    return Image(original, original[:HEADER_LEN], compressed, unpacked, flash, ram)


def rebuild_same_application(img: Image) -> bytes:
    compressed = pack_lzss2(img.unpacked)
    header = bytearray(img.header)
    struct.pack_into('>I', header, HEADER_LEN-4, len(compressed))
    prefix = bytes(header) + compressed
    crc = crc32_netos(prefix)
    rebuilt = prefix + crc.to_bytes(4, 'big')
    checked = read_image(rebuilt)
    if checked.unpacked != img.unpacked:
        raise ValidationError('Rebuilt firmware differs in application bytes')
    if checked.flash_offset != img.flash_offset or checked.ram_address != img.ram_address:
        raise ValidationError('Rebuilt image changed address fields')
    return rebuilt


def load_zip(path: Path) -> tuple[str, bytes]:
    with zipfile.ZipFile(path) as zf:
        infos = zf.infolist()
        if len(infos) > 64 or any(m.file_size > MAX_INPUT_BYTES or m.filename.startswith('/') or '..' in Path(m.filename).parts for m in infos) or sum(m.file_size for m in infos) > 64*1024*1024:
            raise ValidationError('Archive contains unsafe members or excessive uncompressed data')
        failure = zf.testzip()
        if failure:
            raise ValidationError(f'ZIP member failed CRC: {failure}')
        members = [m for m in zf.infolist() if m.filename.lower().endswith('.bin')]
        if len(members) != 1 or members[0].file_size > MAX_INPUT_BYTES:
            raise ValidationError('Expected one small BIN in ZIP')
        return members[0].filename, zf.read(members[0])


def sha256(blob: bytes) -> str:
    return hashlib.sha256(blob).hexdigest()


def compare(img: Image, rebuilt: bytes) -> dict:
    dst = read_image(rebuilt)
    a=img.original
    b=dst.original
    return {
        'input_image_bytes': len(a),
        'input_image_sha256': sha256(a),
        'input_compressed_bytes': len(img.compressed),
        'rebuild_image_bytes': len(b),
        'rebuild_image_sha256': sha256(b),
        'rebuild_compressed_bytes': len(dst.compressed),
        'compressed_delta_bytes': len(dst.compressed) - len(img.compressed),
        'compression_size_within_original': len(dst.compressed) <= len(img.compressed),
        'rebuild_is_original_byte_exact': a == b,
        'rebuild_is_application_byte_exact': img.unpacked == dst.unpacked,
        'rebuild_crc_valid': crc32_netos(b) == 0,
        'application_bytes': len(img.unpacked),
        'application_sha256': sha256(img.unpacked),
        'header_fields_preserved_except_length': img.header[:32] == dst.header[:32],
        'flash_offset': f'0x{img.flash_offset:08x}',
        'ram_address': f'0x{img.ram_address:08x}',
        'flash_safety_status': 'NOT FLASH APPROVED - flash/RAM capacity, uploader checks, recovery, and boot unverified'
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('archives', type=Path, nargs='+')
    ap.add_argument('--output', type=Path, default=Path('reports'))
    ap.add_argument('--write-offline-rebuilds', action='store_true', help='Write only .offline-test-image files; never flash')
    args = ap.parse_args(argv)
    args.output.mkdir(parents=True, exist_ok=True)
    try:
        for archive in args.archives:
            bin_name, original = load_zip(archive)
            img = read_image(original)
            rebuilt = rebuild_same_application(img)
            report = compare(img, rebuilt)
            report['archive'] = archive.name
            report['bin_member'] = bin_name
            (args.output / f'{archive.stem}.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf8')
            if args.write_offline_rebuilds:
                (args.output / f'{archive.stem}.offline-test-image').write_bytes(rebuilt)
            print(f"{archive.name}: app exact={report['rebuild_is_application_byte_exact']} "
                  f"CRC={report['rebuild_crc_valid']} "
                  f"original {report['input_compressed_bytes']:,} -> rebuilt {report['rebuild_compressed_bytes']:,} compressed bytes")
        return 0
    except (OSError, ValidationError, zipfile.BadZipFile) as e:
        print(f'FAIL: {e}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
